function enrichWithMandatoryKLColumns(item: ComplaintItem): ComplaintItem {
  let kHeader = item.mainHeader;
  let lTopic = item.subTopic;

  if (!kHeader || kHeader.startsWith("SRV-") || kHeader.startsWith("CMP-") || /^\d+$/.test(kHeader)) {
    const text = `${item.complaintSubject || ""} ${item.rawComplaintText || ""} ${item.faultCategory || ""}`.toLowerCase();
    if (text.includes("yağ") || text.includes("külbütör") || text.includes("karter") || text.includes("sızıntı")) {
      kHeader = "Motor & Yağlama Sistemi";
      lTopic = lTopic || "Külbütör Kapağı Yağ Sızıntısı";
    } else if (text.includes("zincir") || text.includes("triger") || text.includes("eksantrik")) {
      kHeader = "Triger & Eksantrik Sistemi";
      lTopic = lTopic || "Eksantrik Zincir Aşınması & Ses";
    } else if (text.includes("şanzıman") || text.includes("kavrama") || text.includes("dsg") || text.includes("edc") || text.includes("mekatronik") || text.includes("vites")) {
      kHeader = "Şanzıman & Çift Kavrama";
      lTopic = lTopic || "Mekatronik Basınç Kaybı & Kavrama Titremesi";
    } else if (text.includes("termostat") || text.includes("antifriz") || text.includes("soğutma") || text.includes("hararet") || text.includes("radyatör")) {
      kHeader = "Soğutma & Termostat Sistemi";
      lTopic = lTopic || "Termostat Flanş Çatlağı & Antifriz Eksiltme";
    } else if (text.includes("adblue") || text.includes("dpf") || text.includes("emisyon") || text.includes("egzoz") || text.includes("partikül")) {
      kHeader = "Egzoz, DPF & AdBlue Emisyon";
      lTopic = lTopic || "DPF Tıkanıklığı & AdBlue Pompa Arızası";
    } else if (text.includes("fren") || text.includes("balata") || text.includes("disk") || text.includes("abs")) {
      kHeader = "Fren Sistemi & ABS";
      lTopic = lTopic || "Fren Balatası Aşınması & Disk Titreşimi";
    } else if (text.includes("süspansiyon") || text.includes("salıncak") || text.includes("amortisör") || text.includes("rot")) {
      kHeader = "Süspansiyon & Yürüyen Aksam";
      lTopic = lTopic || "Salıncak Burcu Boşluğu & Ses";
    } else if (text.includes("elektrik") || text.includes("akü") || text.includes("alternatör") || text.includes("sensör") || text.includes("beyin") || text.includes("marş")) {
      kHeader = "Elektrik & Elektronik Sistemler";
      lTopic = lTopic || "Akü Şarj Hatası & Sensör Arızası";
    } else if (text.includes("klima") || text.includes("kompresör") || text.includes("soğutmuyor")) {
      kHeader = "Klima & İklimlendirme";
      lTopic = lTopic || "Klima Kompresörü Devre Dışı & Gaz Kaçağı";
    } else if (text.includes("turbo") || text.includes("intercooler") || text.includes("hortum")) {
      kHeader = "Turbo & Emiş Sistemi";
      lTopic = lTopic || "Turbo Basınç Hortumu Yırtığı";
    } else if (text.includes("enjektör") || text.includes("yakıt") || text.includes("pompa")) {
      kHeader = "Yakıt & Enjeksiyon Sistemi";
      lTopic = lTopic || "Enjektör Geri Dönüş Kaçağı";
    } else {
      kHeader = item.faultCategory || "Genel Mekanik Sistemler";
      lTopic = lTopic || item.complaintSubject || "Periyodik Kontrol & Arıza";
    }
  }

  if (!lTopic || lTopic.startsWith("SRV-") || lTopic.startsWith("CMP-") || /^\d+$/.test(lTopic)) {
    lTopic = item.complaintSubject || "Genel Arıza Şikayeti";
  }

  return {
    ...item,
    mainHeader: kHeader,
    subTopic: lTopic,
    complaintReason: lTopic,
  };
}

